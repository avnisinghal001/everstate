const ICONS = {
  session: [
    "..#####..", ".#.....#.", "#...#...#", "#...#...#", "#...###.#", "#.......#", "#.......#", ".#.....#.", "..#####..",
  ],
  dream: [
    "...####..", "..##.....", ".##......", ".##......", ".##......", ".##....#.", "..##..##.", "...####..", ".........",
  ],
  memory: [
    "#########", "#.......#", "#########", ".........", "#########", "#.......#", "#########", ".........", "#########",
  ],
  rules: [
    "#########", "#.......#", "#.#####.#", "#.#...#.#", "#.#.#.#.#", "#.#...#.#", "#.#####.#", "#.......#", "#########",
  ],
  feedback: [
    "...###...", ".##...##.", "#.......#", "#....#..#", "#...###.#", "#.......#", ".##...##.", "...###...", "....#....",
  ],
  forget: [
    "#########", "...#.#...", ".#######.", ".#.#.#.#.", ".#.#.#.#.", ".#.#.#.#.", ".#.#.#.#.", ".#######.", ".........",
  ],
  support: [
    ".#######.", "#.......#", "#.#.#.#.#", "#.......#", ".###.###.", "....#....", "...#.....", "..#......", ".........",
  ],
  code: [
    ".........", "..#...#..", ".#.....#.", "#...#...#", "...#.....", "..#...#..", ".#.....#.", "#.......#", ".........",
  ],
  company: [
    "....#....", "...###...", "..#####..", ".#.#.#.#.", ".#######.", ".#.#.#.#.", ".#######.", ".#.#.#.#.", "#########",
  ],
  person: [
    "...###...", "..#####..", "..#####..", "...###...", ".........", ".#######.", "#########", "#########", "#########",
  ],
} as const;

export type PictogramName = keyof typeof ICONS;

export function Pictogram({ name, size = 4 }: { name: PictogramName; size?: number }) {
  const rows = ICONS[name];
  return (
    <div className="pict" style={{ gridTemplateColumns: `repeat(9, ${size}px)` }} aria-hidden="true">
      {rows.flatMap((row, r) => [...row].map((c, i) => (
        <i key={`${r}-${i}`} className={c === "#" ? "" : "o"} style={{ inlineSize: size, blockSize: size }} />
      )))}
    </div>
  );
}
